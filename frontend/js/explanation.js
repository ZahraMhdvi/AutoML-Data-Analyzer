function getProblemExplanation(type){


    if(!type)
        return null;



    return problemExplanations[
        type.toLowerCase()
    ];

}







function getScoreText(score){


    if(score >= 80)

        return "بسیار مناسب";



    if(score >= 60)

        return "مناسب";



    if(score >= 40)

        return "قابل بررسی";



    return "نیاز به بررسی بیشتر";

}






