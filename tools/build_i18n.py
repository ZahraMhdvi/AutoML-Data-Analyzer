def build():
    tree = dict(TREE)
    tree["errors"] = {code: P(message.replace("{", "{").replace("}", "}"), ERRORS_FA[code])
                      for code, message in ERROR_MESSAGES.items()}
    tree["errors"].update(EXTRA_ERRORS)

    def split(node, index):
        if isinstance(node, tuple):
            return node[index]
        return {key: split(value, index) for key, value in node.items()}

    en, fa = split(tree, 0), split(tree, 1)

    def keys(node, prefix=""):
        if isinstance(node, dict):
            out = set()
            for key, value in node.items():
                out |= keys(value, f"{prefix}.{key}" if prefix else key)
            return out
        return {prefix}

    assert keys(en) == keys(fa), keys(en) ^ keys(fa)

    out_dir = os.path.join(ROOT, "frontend", "i18n")
    os.makedirs(out_dir, exist_ok=True)
    for name, data in (("en-US", en), ("fa-IR", fa)):
        with open(os.path.join(out_dir, f"{name}.json"), "w", encoding="utf-8") as handle:
            json.dump(data, handle, ensure_ascii=False, indent=2)
    print(f"wrote {len(keys(en))} keys per locale")


if __name__ == "__main__":
    build()
